#!/usr/bin/env bash
#
# Extract the Xiaomi vendor blobs for sakura into a LineageOS-style vendor tree.
#
# Two sources are supported:
#   1. a connected device running a stock Android 10 / LineageOS 17.1 build (adb)
#   2. an extracted LineageOS 17.1 ROM zip (system.img / vendor.img already unpacked)
#
# The blobs are only needed if you want to rebuild the Halium GSI or a device-specific
# Android system image. The flashable zip produced by this project uses the prebuilt
# generic Halium 10 GSI, so this script is optional for the normal build path.
#
# Usage:
#   scripts/extract-blobs.sh --adb                  pull from a connected device
#   scripts/extract-blobs.sh --dir <unpacked-rom>   copy from an unpacked ROM
#   scripts/extract-blobs.sh --list <unpacked-rom>  print what would be copied
#
# Output tree:
#   vendor/xiaomi/sakura/proprietary/...            blobs
#   vendor/xiaomi/sakura/sakura-vendor.mk           makefile stub with PRODUCT_COPY_FILES
#
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/vendor/xiaomi/sakura"
MODE=""
SRC=""

# Directories worth pulling from a stock sakura Android 10 build. Extend as the port
# needs more HALs; the list is intentionally explicit so the output stays reviewable.
ADB_PATHS=(
    /vendor/lib64/hw
    /vendor/lib/hw
    /vendor/lib64
    /vendor/lib
    /vendor/etc
    /vendor/firmware_mnt
    /vendor/bin/hw
    /system/etc/firmware
    /system/vendor/firmware
)

usage() {
    sed -n '2,30p' "$0" | sed 's/^# \{0,1\}//'
    exit 1
}

while [ $# -gt 0 ]; do
    case "$1" in
        --adb) MODE="adb" ;;
        --dir) MODE="dir"; SRC="$2"; shift ;;
        --list) MODE="list"; SRC="$2"; shift ;;
        -h|--help) usage ;;
        *) echo "extract-blobs: unknown option $1" >&2; usage ;;
    esac
    shift
done
[ -n "$MODE" ] || usage

mkdir -p "$OUT/proprietary"

if [ "$MODE" = "adb" ]; then
    command -v adb >/dev/null || { echo "extract-blobs: adb not found" >&2; exit 1; }
    if ! adb get-state >/dev/null 2>&1; then
        echo "extract-blobs: no device visible to adb" >&2
        exit 1
    fi
    echo "==> Pulling from $(adb shell getprop ro.product.device | tr -d '\r')"
    for path in "${ADB_PATHS[@]}"; do
        dest="$OUT/proprietary/${path#/}"
        mkdir -p "$(dirname "$dest")"
        echo "    $path -> $dest"
        adb pull "$path" "$dest" >/dev/null 2>&1 || echo "    (skipped, not present)"
    done
    echo "==> Blobs written to $OUT/proprietary"
    exit 0
fi

# --dir / --list: copy from an unpacked ROM tree
[ -d "$SRC" ] || { echo "extract-blobs: $SRC is not a directory" >&2; exit 1; }

echo "==> Scanning $SRC"
found=0
while IFS= read -r -d '' f; do
    rel="${f#"$SRC"/}"
    case "$rel" in
        vendor/*|system/vendor/*|system/lib*|system/etc/firmware/*|system/bin/hw/*) ;;
        *) continue ;;
    esac
    found=$((found + 1))
    if [ "$MODE" = "list" ]; then
        echo "    $rel"
    else
        mkdir -p "$OUT/proprietary/$(dirname "$rel")"
        cp -a "$f" "$OUT/proprietary/$rel"
    fi
done < <(find "$SRC" -type f -print0)

echo "==> $found files matched"
if [ "$MODE" = "dir" ]; then
    {
        echo "# Automatically generated by scripts/extract-blobs.sh"
        echo "# Regenerate with: scripts/extract-blobs.sh --dir <unpacked-rom>"
        echo "PRODUCT_COPY_FILES += \\"
        (cd "$OUT/proprietary" && find . -type f | sed 's|^\./||' | sort | \
            awk 'BEGIN{last=""} {printf "    $(LOCAL_PATH)/proprietary/%s:$(TARGET_COPY_OUT_VENDOR)/%s \\\n", $0, substr($0, index($0,"/")+1)}')
    } > "$OUT/sakura-vendor.mk"
    echo "==> Wrote $OUT/sakura-vendor.mk"
fi
